export const PAIR_CONTENT: ReadonlyMap<string, PairContent> = new Map(
  ROWS.map(([a, b, name, together, deokdam]) => [
    pairKey(a, b),
    { name, together, deokdam },
  ])
);

export const PAIR_COUNT = ROWS.length;

const TIERS = [
  { min: 85, label: "천생연분" },
  { min: 72, label: "죽이 잘 맞는 사이" },
  { min: 62, label: "달라서 재밌는 사이" },
  { min: 0, label: "티격태격하는 사이" },
] as const;

export type PairReading = PairContent & {
  score: number;
  tier: string;
  /** 조심할 달 (1~12). 두 유형의 행운의 달과 겹치지 않게 규칙으로 정한다. */
  carefulMonth: number;
};

export function readPair(aId: SheepTypeId, bId: SheepTypeId): PairReading {
  const a = getSheepType(aId);
  const b = getSheepType(bId);
  const score = pairScore(a, b);
  let carefulMonth = ((a.luckyMonth + b.luckyMonth + 5) % 12) + 1;
  while (carefulMonth === a.luckyMonth || carefulMonth === b.luckyMonth) {
    carefulMonth = (carefulMonth % 12) + 1;
  }
  return {
    ...PAIR_CONTENT.get(pairKey(aId, bId))!,
    score,
    tier: TIERS.find((t) => score >= t.min)!.label,
    carefulMonth,
  };
}
