export type Card = {
  id: string;
  theme: CardThemeKey;
  themeLabel: string;
  color: string;
  name: string;
  fortune: string;
  deokdam: string;
  gold: boolean;
};

export const CARDS: readonly Card[] = CARD_THEMES.flatMap((theme) =>
  ROWS[theme.key].map(([name, fortune, deokdam], i, rows) => ({
    id: `${theme.key}-${String(i + 1).padStart(2, "0")}`,
    theme: theme.key,
    themeLabel: theme.label,
    color: theme.color,
    name,
    fortune,
    deokdam,
    gold: i === rows.length - 1,
  }))
);

const BY_ID = new Map(CARDS.map((c) => [c.id, c]));

export function getCard(id: string): Card | undefined {
  return BY_ID.get(id);
}

const NORMAL_WEIGHT = 4;
const GOLD_WEIGHT = 1;

/**
 * 오늘의 카드를 고른다. 아직 안 모은 카드에서 먼저 뽑고, 황금 카드는 4분의 1 확률로 나온다.
 * random은 0 이상 1 미만의 수(기본은 Math.random).
 */
export function pickCard(
  ownedIds: ReadonlySet<string>,
  random: () => number = Math.random
): Card {
  const fresh = CARDS.filter((c) => !ownedIds.has(c.id));
  const pool = fresh.length > 0 ? fresh : CARDS;
  const total = pool.reduce((sum, c) => sum + (c.gold ? GOLD_WEIGHT : NORMAL_WEIGHT), 0);
  let roll = random() * total;
  for (const card of pool) {
    roll -= card.gold ? GOLD_WEIGHT : NORMAL_WEIGHT;
    if (roll < 0) return card;
  }
  return pool[pool.length - 1];
}
